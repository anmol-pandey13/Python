# Python Data Types

name = "Anmol"          # String
age = 20                # Integer
temperature = 28.5      # Float
is_raining = False      # Boolean

skills = ["Python", "Pandas", "Streamlit"]  # List

student = {
    "name": "Anmol",
    "age": 20,
    "course": "Computer Science"
}  # Dictionary

print(type(name))
print(type(age))
print(type(temperature))
print(type(is_raining))
print(type(skills))
print(type(student))